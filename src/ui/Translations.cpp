juce::String russianTranslations()
{
    juce::String text ("language: Russian\ncountries: ru\n\n");
    for (const auto& pair : pairs)
        text << "\"" << escape (pair.english) << "\" = \"" << escape (pair.russian) << "\"\n";
    return text;
}

